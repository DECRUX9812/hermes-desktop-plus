export const GLYPH_W = 6 // 5px + 1 space

/**
 * Draw one line of text; returns pixel width. `scale` multiplies pixels
 * (integer). Colors as CSS strings.
 */
export function drawText(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, scale: number, color: string): number {
  ctx.fillStyle = color
  let cx = x

  for (const ch of text) {
    const code = ch.charCodeAt(0)

    if (code === 10) {break}
    const idx = code - 32

    if (idx >= 0 && idx * 5 < GLYPHS.length) {
      const g = idx * 5

      for (let col = 0; col < 5; col++) {
        const bits = GLYPHS[g + col]

        for (let row = 0; row < 7; row++) {
          if (bits & (1 << row)) {
            ctx.fillRect(cx + col * scale, y + row * scale, scale, scale)
          }
        }
      }
    }

    cx += GLYPH_W * scale
  }

  return cx - x
}

export function textWidth(text: string, scale: number): number {
  return text.length * GLYPH_W * scale
}

/** Wrap text to a pixel width. */
export function wrapText(text: string, maxW: number, scale: number): string[] {
  const words = text.split(/\s+/)
  const lines: string[] = []
  let cur = ''

  for (const w of words) {
    const trial = cur ? cur + ' ' + w : w

    if (textWidth(trial, scale) > maxW && cur) {
      lines.push(cur)
      cur = w
    } else {cur = trial}
  }

  if (cur) {lines.push(cur)}

  return lines
}
